"""3 点が一直線上にあるか判定する。

    isColinear(0, 0, 1, 1, 2, 2)  ->  True
    isColinear(0, 0, 1, 1, 2, 3)  ->  False

仕組み:
    点 3 を原点に平行移動し、ベクトル (x1, y1) と (x2, y2) の外積 x1*y2 - x2*y1 が 0 なら
    2 つのベクトルは平行 = 3 点は同一直線上。
    傾き (y / x) を使わないので、0 除算も浮動小数点の誤差も起きない (整数座標なら厳密)。

注意: 同じ点が 2 つ以上含まれる場合も True になる。
計算量: O(1)。
"""
def isColinear(x1,y1,x2,y2,x3,y3):
    # 点 3 を原点にずらす
    x1 -= x3
    x2 -= x3
    y1 -= y3
    y2 -= y3
    # 外積が 0 なら平行
    if x1 * y2 == x2 * y1:
        return True
    return False